//! Result types for Conversational Query operations.

use crate::clients::conversational_query_client::map_error;
use crate::error;
use crate::results::query_results::{QueryMetrics, QueryStatus, QueryWarning};
use couchbase_core::queryx;
use couchbase_core::results::query::QueryResultStream;
use futures::{Stream, StreamExt};
use serde::de::DeserializeOwned;
use serde_json::value::RawValue;
use std::marker::PhantomData;
use std::pin::Pin;
use std::task::{Context, Poll};
use std::time::Duration;

/// Token counts reported by Query for model usage.
#[derive(Debug, Clone, Default, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub struct ConversationalTokenUsage {
    /// Tokens in the prompts sent to the model.
    pub prompt_tokens: Option<u64>,
    /// Tokens generated by the model.
    pub completion_tokens: Option<u64>,
    /// Total tokens.
    pub total_tokens: Option<u64>,
}

impl From<&queryx::query_result::TokenUsage> for ConversationalTokenUsage {
    fn from(usage: &queryx::query_result::TokenUsage) -> Self {
        Self {
            prompt_tokens: usage.prompt_tokens,
            completion_tokens: usage.completion_tokens,
            total_tokens: usage.total_tokens,
        }
    }
}

/// Metadata returned by Conversational Query operations.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct ConversationalMetaData {
    /// The server-assigned request id.
    pub request_id: String,
    /// The client context id.
    pub client_context_id: String,
    /// The execution status.
    pub status: QueryStatus,
    /// Warnings returned by Query.
    pub warnings: Vec<QueryWarning>,
    /// Query metrics, present when metrics were requested.
    pub metrics: Option<QueryMetrics>,
    /// Profiling information, present when profiling was requested.
    pub profile: Option<Box<RawValue>>,
    /// Token usage for this request.
    pub request_tokens: Option<ConversationalTokenUsage>,
    /// Cumulative token usage for the chat.
    pub chat_tokens: Option<ConversationalTokenUsage>,
    /// Time spent on natural-language processing, when metrics were returned.
    pub natural_language_processing_time: Option<Duration>,
    /// Whether the generated statement was executed, when metrics were returned.
    pub generated_statement_executed: Option<bool>,
}

impl From<&queryx::query_result::MetaData> for ConversationalMetaData {
    fn from(meta: &queryx::query_result::MetaData) -> Self {
        Self {
            request_id: meta.request_id.clone(),
            client_context_id: meta.client_context_id.clone(),
            status: meta.status.into(),
            warnings: meta.warnings.iter().cloned().map(Into::into).collect(),
            metrics: meta.metrics.as_ref().map(QueryMetrics::from),
            profile: meta.profile.clone(),
            request_tokens: meta
                .request_tokens
                .as_ref()
                .map(ConversationalTokenUsage::from),
            chat_tokens: meta
                .chat_tokens
                .as_ref()
                .map(ConversationalTokenUsage::from),
            natural_language_processing_time: meta
                .metrics
                .as_ref()
                .and_then(|m| m.natural_language_processing_time),
            generated_statement_executed: meta
                .metrics
                .as_ref()
                .and_then(|m| m.generated_statement_executed),
        }
    }
}

/// The result of [`ConversationalQuery::query`](crate::conversational_query::ConversationalQuery::query)
/// or [`ConversationalQueryChat::ask`](crate::conversational_query::ConversationalQueryChat::ask).
///
/// Rows are handled like ordinary query rows. The generated statement is available without
/// reading any rows.
pub struct ConversationalResult {
    wrapped: QueryResultStream,
}

impl std::fmt::Debug for ConversationalResult {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ConversationalResult")
            .field("generated_statement", &self.generated_statement())
            .finish_non_exhaustive()
    }
}

impl From<QueryResultStream> for ConversationalResult {
    fn from(wrapped: QueryResultStream) -> Self {
        Self { wrapped }
    }
}

impl ConversationalResult {
    /// Returns the generated statement, when Query returned one.
    pub fn generated_statement(&self) -> Option<&str> {
        // Query sends the statement before any results, so it is in the early metadata.
        self.wrapped.early_metadata().generated_statement.as_deref()
    }

    /// Returns the metadata. Only available once all rows have been read.
    pub fn metadata(&self) -> error::Result<ConversationalMetaData> {
        Ok(self.wrapped.metadata().map_err(map_error)?.into())
    }

    /// Returns a [`Stream`] of deserialized result rows.
    pub fn rows<'a, V: DeserializeOwned + 'a>(
        &'a mut self,
    ) -> impl Stream<Item = error::Result<V>> + 'a {
        ConversationalQueryRows {
            wrapped: &mut self.wrapped,
            phantom_data: PhantomData,
        }
    }
}

struct ConversationalQueryRows<'a, V: DeserializeOwned> {
    wrapped: &'a mut QueryResultStream,
    phantom_data: PhantomData<&'a V>,
}

impl<V: DeserializeOwned> Stream for ConversationalQueryRows<'_, V> {
    type Item = error::Result<V>;

    fn poll_next(mut self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<Option<Self::Item>> {
        match self.wrapped.poll_next_unpin(cx) {
            Poll::Ready(Some(Ok(row))) => Poll::Ready(Some(
                serde_json::from_slice(&row).map_err(error::Error::decoding_failure_from_serde),
            )),
            Poll::Ready(Some(Err(e))) => Poll::Ready(Some(Err(map_error(e)))),
            Poll::Ready(None) => Poll::Ready(None),
            Poll::Pending => Poll::Pending,
        }
    }
}
